# P-card pseudo-checks begin 926; payroll warrants are 530xxx. Both were
# confirmed against the 2026 sets rather than assumed from the brief.
PCARD_PREFIX = "926"
PAYROLL_PREFIX = "530"

# A check number this corpus uses as a sentinel for a credit rather than as
# an actual warrant. Confirmed on 2026-05-27 ACH: check 8888888888,
# Electrocom Inc, six rows summing to zero invoice against -$2,887.19.
SENTINEL_CHECK_NUMBERS = {"8888888888", "9999999999"}


@dataclass
class SetRow:
    """One voucher set, ready to write.

    Attributes:
        set_id: Stable identifier, ``<meeting_date>:<fund>``.
        artifact: The census artifact it came from.
        parsed: The parser's output.
        lines: Parsed line rows.
    """

    set_id: str
    artifact: object
    parsed: ParsedListing
    lines: list = field(default_factory=list)
    stated_total: Decimal | None = None
    parsed_total: Decimal = Decimal("0")
    sum_check_dedup: Decimal = Decimal("0")
    check_count: int = 0
    hash_total: int = 0
    reconciled: bool | None = None
    delta: Decimal | None = None
    reason_code: str | None = None
    notes: list[str] = field(default_factory=list)
    fund: str | None = None
    stated_total_page: int | None = None


def choose_fund(artifact, parsed: ParsedListing, first_page: str) -> tuple[str | None, str | None]:
    """Decide a set's fund, preferring the printed header over the file name.

    Args:
        artifact: Census artifact carrying the title-derived fund.
        parsed: Parser output (unused today; kept for symmetry).
        first_page: Text of page 1.

    Returns:
        ``(fund, note)`` where note is set when the two signals disagree.
    """
    from_text = fund_from_text(first_page)
    from_title = artifact.fund
    if from_text and from_title and from_text != from_title:
        return from_text, (
            f"fund disagreement: file name says {from_title}, printed header says {from_text}; the header wins"
        )
    return (from_text or from_title), None


def build_lines(set_id: str, artifact, parsed: ParsedListing, pdf: PdfText) -> list[dict]:
    """Turn parsed rows into ``facts.voucher_line`` dicts.

    Args:
        set_id: Owning set.
        artifact: Census artifact, for provenance.
        parsed: Parser output.
        pdf: The extracted PDF, for page lookup.

    Returns:
        One dict per line, in document order.
    """
    source = source_kind(artifact.resolved_path)
    out: list[dict] = []
    for seq, row in enumerate(parsed.rows, start=1):
        number = row.check_number or ""
        out.append(
            {
                "set_id": set_id,
                "line_seq": seq,
                "vendor_raw": row.vendor_raw,
                "vendor_norm": normalize_vendor(row.vendor_raw),
                "check_date": row.check_date,
                "check_number": row.check_number,
                "check_amount": row.check_amount,
                "invoice_amount": row.invoice_amount,
                "description": row.description or None,
                "is_pcard": number.startswith(PCARD_PREFIX),
                "is_payroll_warrant": number.startswith(PAYROLL_PREFIX) and len(number) == 6,
                "is_person_shaped": is_person_shaped(row.vendor_raw),
                "is_credit": (row.invoice_amount is not None and row.invoice_amount < 0)
                or number in SENTINEL_CHECK_NUMBERS,
                "source": source,
                "locator_document_id": artifact.document_id,
                "locator_file_path": artifact.resolved_path,
                "locator_file_sha256": artifact.sha256,
                "locator_page": pdf.page_for_offset(row.char_offset),
                "locator_char_offset": row.char_offset,
                "locator_quote": make_quote(pdf.text, row.char_offset, row.char_end),
            }
        )
    return out


def summarize(row: SetRow) -> None:
    """Compute the three control totals and the reconciliation verdict.

    ``reconciled`` has three states and they are not interchangeable:
    true when the lines sum to a stated total to the cent, false when they
    sum to something else, and NULL when the document states no total to
    reconcile against. 303 listings from 2017-2022 are in the third case,
    and marking them false would assert the district's arithmetic is wrong
    when what is true is that the document states no arithmetic.

    Args:
        row: The set to summarize, mutated in place.
    """
    seen: dict[str, Decimal] = {}
    total = Decimal("0")
    for line in row.lines:
        if line["invoice_amount"] is not None:
            total += line["invoice_amount"]
        number = line["check_number"]
        if number and number not in seen:
            seen[number] = line["check_amount"] or Decimal("0")
            if number.isdigit():
                row.hash_total += int(number)
    row.parsed_total = total
    row.sum_check_dedup = sum(seen.values(), Decimal("0"))
    row.check_count = len(seen)
    row.stated_total = row.parsed.stated_total

    if not row.lines:
        row.reconciled = False
        row.reason_code = "REGEX_MISS"
        return
    if row.stated_total is None:
        # Nothing to check against. Not a failure of the parse, and not a
        # claim that the set is wrong.
        row.reconciled = None
        row.reason_code = "TOTAL_NOT_FOUND"
        return
    row.delta = row.parsed_total - row.stated_total
    if row.delta == 0:
        row.reconciled = True
        if row.parsed.extra_totals:
            row.notes.append(
                f"{len(row.parsed.extra_totals)} further TOTAL line(s) after the chosen "
                f"one: {', '.join(str(a) for _, a, _ in row.parsed.extra_totals)}. The "
                f"chosen total is the first after the last data row and it reconciles."
            )
        return
    row.reconciled = False
    row.reason_code = "MULTIPLE_TOTALS" if row.parsed.extra_totals else "OUT_OF_BALANCE"


def mark_cumulative(sets: list[SetRow]) -> None:
    """Record, per set, how many of its checks appeared in an earlier set.

    A listing that restates prior cycles is not an error, but summing such
    listings across meetings double-counts real money. The overlap is
    measured by check number against every earlier set of the same fund, so
    the finding is a property of the document rather than of its era.

    Args:
        sets: All sets, any order. Mutated in place.
    """
    by_fund: dict[str, list[SetRow]] = defaultdict(list)
    for row in sets:
        if row.fund:
            by_fund[row.fund].append(row)

    for fund, rows in by_fund.items():
        rows.sort(key=lambda r: r.artifact.meeting_date or "")
        seen: set[str] = set()
        for row in rows:
            numbers = {line["check_number"] for line in row.lines if line["check_number"]}
            repeated = numbers & seen
            if repeated:
                repeated_amount = sum(
                    (line["invoice_amount"] or Decimal("0") for line in row.lines if line["check_number"] in repeated),
                    Decimal("0"),
                )
                row.notes.append(
                    f"cumulative: {len(repeated)} of {len(numbers)} check numbers "
                    f"({repeated_amount} of {row.parsed_total}) already appeared in an "
                    f"earlier {fund} set. Summing this set with earlier ones "
                    f"double-counts that money."
                )
            seen |= numbers


def reconcile_against_register(
    sets_by_date: dict[str, list[SetRow]],
    registers: dict[str, list[dict]],
    recaps: dict[str, list[dict]],
) -> list[dict]:
    """Cross-check each set against the signed register, where one exists.

    Three bases are computed, and which one applies depends on the fund:

    ``ap_direct_deposit``
        The ACH listing total equals the sum of every accounts-payable
        direct-deposit line in the register, across all funds. Verified
        exactly on 2026-03-25.
    ``warrants_plus_pcard``
        A fund listing equals that fund's accounts-payable warrant ranges
        plus its purchasing-card line. Exact for Capital on 2026-03-25;
        ASB differs by two warrants that are on the register and not in the
        listing, which is the kind of fact this table exists to hold.
    ``recap_fund_total``
        Where no register exists but a Warrant Recap does, its per-fund
        total is recorded. The recap is register scope, so equality is not
        expected for funds that carry payroll or electronic transfers.

    Args:
        sets_by_date: Sets grouped by meeting date.
        registers: Parsed registers, keyed by meeting date.
        recaps: Parsed recap fund totals, keyed by meeting date.

    Returns:
        ``facts.voucher_reconciliation`` dicts.
    """
    out: list[dict] = []
    for meeting_date, rows in sets_by_date.items():
        register = registers.get(meeting_date)
        recap = recaps.get(meeting_date)
        for row in rows:
            if row.fund is None or not row.lines:
                continue
            if register:
                record = _register_basis(row, register)
                if record:
                    out.append(record)
            elif recap:
                record = _recap_basis(row, recap)
                if record:
                    out.append(record)
    return out


def _register_basis(row: SetRow, register: dict) -> dict | None:
    """Compare one set against the signed register.

    Args:
        row: The set.
        register: Parsed register, with ``lines`` and ``fund_totals``.

    Returns:
        A reconciliation dict, or None when no basis applies.
    """
    lines = register["lines"]
    meta = register["meta"]
    if row.fund == "ACH":
        relevant = [line for line in lines if line["is_direct_deposit"] and line["is_accounts_payable"]]
        basis = "ap_direct_deposit"
        ranges = None
    else:
        # The listing holds warrants and P-card pseudo-checks. It does NOT
        # hold the register's other electronic transfers -- DOR use taxes,
        # L&I self-insurance, direct deposits -- so the basis is exactly the
        # lines that carry a warrant range, plus the purchasing-card line.
        # Phase 0 proved this basis ties Capital to the cent on 2026-03-25
        # and leaves ASB short by exactly two warrants that the register
        # carries and the listing does not.
        relevant = [
            line
            for line in lines
            if line["fund"] == row.fund
            and not line["is_payroll"]
            and line["is_accounts_payable"]
            and (line["warrant_range"] or line["is_pcard"])
        ]
        basis = "warrants_plus_pcard"
        ranges = ",".join(line["warrant_range"] for line in relevant if line["warrant_range"]) or None
    if not relevant:
        return None
    register_total = sum((line["amount"] for line in relevant), Decimal("0"))
    delta = row.parsed_total - register_total
    first = relevant[0]
    return {
        "set_id": row.set_id,
        "basis": basis,
        "register_document_id": meta["document_id"],
        "register_file_path": meta["path"],
        "register_file_sha256": meta["sha256"],
        "register_total": register_total,
        "register_warrant_range": ranges,
        "detail_total": row.parsed_total,
        "match": delta == 0,
        "delta": delta,
        "reason": "MATCH" if delta == 0 else "REGISTER_MISMATCH",
        "notes": None
        if delta == 0
        else (
            f"{len(relevant)} register line(s) totalling {register_total} against a "
            f"listing of {row.parsed_total}. Recorded, not resolved."
        ),
        # The set's own TOTAL locator lives on facts.voucher_set; here only
        # the offset is repeated, so the two sides can be read together.
        "locator_detail_page": None,
        "locator_detail_char_offset": row.parsed.stated_total_offset,
        "locator_detail_quote": None,
        "locator_register_page": meta["page_for_offset"](first["offset"]),
        "locator_register_char_offset": first["offset"],
        "locator_register_quote": first["text"][:300],
    }


def _recap_basis(row: SetRow, recap: dict) -> dict | None:
    """Compare one set against a Warrant Recap fund total.

    Args:
        row: The set.
        recap: Parsed recap, with ``fund_totals`` and ``meta``.

    Returns:
        A reconciliation dict, or None when the recap names no such fund.
    """
    meta = recap["meta"]
    match = next((t for t in recap["fund_totals"] if t["fund"] == row.fund), None)
    if match is None:
        return None
    delta = row.parsed_total - match["amount"]
    return {
        "set_id": row.set_id,
        "basis": "recap_fund_total",
        "register_document_id": meta["document_id"],
        "register_file_path": meta["path"],
        "register_file_sha256": meta["sha256"],
        "register_total": match["amount"],
        "register_warrant_range": None,
        "detail_total": row.parsed_total,
        "match": delta == 0,
        "delta": delta,
        # The recap is register scope: it includes payroll and electronic
        # transfers the listing never shows. A difference is expected for
        # funds that carry them, so it is not called a mismatch.
        "reason": "MATCH" if delta == 0 else "SCOPE_DIFFERS",
        "notes": "Warrant Recap totals are register scope, not listing scope.",
        "locator_detail_page": None,
        "locator_detail_char_offset": row.parsed.stated_total_offset,
        "locator_detail_quote": None,
        "locator_register_page": meta["page_for_offset"](match["offset"]),
        "locator_register_char_offset": match["offset"],
        "locator_register_quote": match["quote"],
    }


def build_vendors(all_lines: list[dict], set_dates: dict[str, date]) -> list[dict]:
    """Aggregate ``facts.vendor`` from the parsed lines.

    Args:
        all_lines: Every voucher line.
        set_dates: Meeting date of each set.

    Returns:
        One dict per distinct ``vendor_norm``.
    """
    agg: dict[str, dict] = {}
    for line in all_lines:
        norm = line["vendor_norm"]
        entry = agg.get(norm)
        when = set_dates.get(line["set_id"])
        if entry is None:
            entry = agg[norm] = {
                "vendor_norm": norm,
                "display_name": line["vendor_raw"],
                "aliases": set(),
                "is_person_shaped": line["is_person_shaped"],
                "first_seen": when,
                "last_seen": when,
                "line_count": 0,
                "total_invoice": Decimal("0"),
                "observed_locator_document_id": line["locator_document_id"],
                "observed_locator_file_path": line["locator_file_path"],
                "observed_locator_file_sha256": line["locator_file_sha256"],
                "observed_locator_page": line["locator_page"],
                "observed_locator_char_offset": line["locator_char_offset"],
                "observed_locator_quote": line["locator_quote"],
            }
        entry["aliases"].add(line["vendor_raw"])
        entry["line_count"] += 1
        if line["invoice_amount"] is not None:
            entry["total_invoice"] += line["invoice_amount"]
        if when:
            if entry["first_seen"] is None or when < entry["first_seen"]:
                entry["first_seen"] = when
            if entry["last_seen"] is None or when > entry["last_seen"]:
                entry["last_seen"] = when
    for entry in agg.values():
        # The display name is the most common spelling, chosen by frequency
        # only -- never edited, never title-cased. "KCDA" must not become
        # "Kcda".
        entry["aliases"] = sorted(entry["aliases"])
        entry["display_name"] = max(entry["aliases"], key=len) if entry["aliases"] else entry["display_name"]
    return list(agg.values())


