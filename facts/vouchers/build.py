"""Build the voucher fact tables from the source PDFs.

Reads ``documents`` read-only, reads PDFs from every corpus and staging
root, and writes only to schema ``facts``.

Two things here are deliberate and worth reading before changing:

**Fund comes from the printed header, not the file name, wherever the
header exists.** ``TVF_Vouchers_02-11-26.pdf`` prints ``Permanent Fund
Warrants``. The file name is typed by a person; the header is generated by
the accounting system.

**"Cumulative" is measured, not inferred from the era.** Phase 0 found that
the 2021-02-10 and 2021-03-10 Transportation listings both total
$1,175,094.00 while their recaps state $783,396.00 and $391,698.00 -- the
listing restates prior cycles. It is tempting to tag a whole era as
cumulative, but the Era C column header is still in use in 2026, so an era
label would wrongly brand current sets. Instead each set is compared against
earlier sets of the same fund by check number, and the overlap is recorded
as a fact about that set.

No LLM is involved in any amount, date, vendor, check-number or total path.
"""

from __future__ import annotations

