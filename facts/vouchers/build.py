def _insert(cursor, schema: str, table: str, columns: tuple[str, ...], rows: list[dict]) -> None:
    """Insert rows with parameter binding, in batches.

    The statement is composed with ``psycopg2.sql`` identifier quoting rather
    than string formatting. The schema, table and column names here are all
    module-level literals and could not carry input, but SQL built by string
    formatting is forbidden in this project regardless of provenance -- the
    rule is worth more than the one exception would save.

    Args:
        cursor: An open psycopg2 cursor.
        schema: Schema name.
        table: Table name.
        columns: Column names, in order.
        rows: Row dicts.
    """
    if not rows:
        return
    statement = sql.SQL("INSERT INTO {}.{} ({}) VALUES %s").format(
        sql.Identifier(schema),
        sql.Identifier(table),
        sql.SQL(", ").join(sql.Identifier(column) for column in columns),
    )
    values = [tuple(row.get(column) for column in columns) for row in rows]
    psycopg2.extras.execute_values(cursor, statement.as_string(cursor), values, page_size=1000)


def main() -> None:
    """Parse every voucher artifact and load schema ``facts``."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reload", action="store_true", help="delete and rebuild all rows")
    parser.add_argument("--only-date", help="restrict to one meeting date")
    parser.add_argument("--progress", action="store_true", help="progress on stderr")
    parser.add_argument("--dry-run", action="store_true", help="parse but write nothing")
    args = parser.parse_args()

    artifacts = census.merge(census.db_artifacts(db.query_dicts), census.disk_artifacts())
    kept = [a for a in artifacts if a.exclusion is None and a.resolved_path]
    if args.only_date:
        kept = [a for a in kept if a.meeting_date == args.only_date]

    agenda_by_date = {row["meeting_date"]: row["document_id"] for row in census.voucher_agenda_items(db.query_dicts)}

    sets: list[SetRow] = []
    logs: list[dict] = []
    registers: dict[str, dict] = {}
    recaps: dict[str, dict] = {}
    used_ids: set[str] = set()

    parseable = [a for a in kept if a.doc_class in {"detail_listing", "warrant_register", "warrant_recap"}]
    for index, artifact in enumerate(parseable, start=1):
        if args.progress and index % 25 == 0:
            print(f"  {index}/{len(parseable)}", file=sys.stderr)
        source = source_kind(artifact.resolved_path)
        base_log = {
            "file_sha256": artifact.sha256,
            "file_path": artifact.resolved_path,
            "document_id": artifact.document_id,
            "meeting_date": artifact.meeting_date,
            "fund": artifact.fund,
            "doc_class": artifact.doc_class,
            "format_era": None,
            "pages": None,
            "lines_found": 0,
            "checks_found": 0,
            "note": None,
            "source": source,
        }
        try:
            pdf = PdfText(artifact.resolved_path)
        except Exception as exc:  # noqa: BLE001 - a corrupt PDF is data, not a crash
            logs.append({**base_log, "status": "unreadable", "note": f"{type(exc).__name__}: {exc}"})
            continue
        base_log["pages"] = pdf.page_count
        if not pdf.has_text_layer:
            logs.append({**base_log, "status": "no_text_layer"})
            continue

        first_page = pdf.pages[0].text if pdf.pages else ""

        if artifact.doc_class == "warrant_register":
            parsed_register = parse_register(pdf.text)
            parsed_register["meta"] = {
                "document_id": artifact.document_id,
                "path": artifact.resolved_path,
                "sha256": artifact.sha256,
                "page_for_offset": pdf.page_for_offset,
            }
            if artifact.meeting_date:
                registers[artifact.meeting_date] = parsed_register
            logs.append(
                {
                    **base_log,
                    "status": "parsed",
                    "lines_found": len(parsed_register["lines"]),
                }
            )
            continue

        if artifact.doc_class == "warrant_recap":
            parsed_recap = parse_register(pdf.text)
            parsed_recap["meta"] = {
                "document_id": artifact.document_id,
                "path": artifact.resolved_path,
                "sha256": artifact.sha256,
                "page_for_offset": pdf.page_for_offset,
            }
            if artifact.meeting_date and parsed_recap["fund_totals"]:
                recaps[artifact.meeting_date] = parsed_recap
            logs.append(
                {
                    **base_log,
                    "status": "parsed" if parsed_recap["fund_totals"] else "total_not_found",
                    "lines_found": len(parsed_recap["fund_totals"]),
                }
            )
            continue

        parsed = parse_listing(pdf.text, first_page, artifact.meeting_date)
        base_log["format_era"] = parsed.era
        if parsed.era is None:
            logs.append({**base_log, "status": "era_unmatched"})
            continue

        fund, note = choose_fund(artifact, parsed, first_page)
        if fund is None:
            logs.append({**base_log, "status": "skipped", "note": "no fund could be determined"})
            continue

        set_id = f"{artifact.meeting_date}:{fund}"
        suffix = 2
        duplicate = False
        while set_id in used_ids:
            set_id = f"{artifact.meeting_date}:{fund}#{suffix}"
            suffix += 1
            duplicate = True
        used_ids.add(set_id)

        row = SetRow(set_id=set_id, artifact=artifact, parsed=parsed, fund=fund)
        if parsed.stated_total_offset is not None:
            row.stated_total_page = pdf.page_for_offset(parsed.stated_total_offset)
        row.lines = build_lines(set_id, artifact, parsed, pdf)
        if note:
            row.notes.append(note)
        if duplicate:
            row.notes.append("a second listing for this fund and meeting; both are kept because their contents differ")
        summarize(row)
        if duplicate and row.reason_code is None:
            row.reason_code = "DUPLICATE_SET"
        sets.append(row)

        status = {
            True: "parsed",
            False: "out_of_balance" if row.lines else "regex_miss",
            None: "total_not_found",
        }[row.reconciled]
        logs.append(
            {
                **base_log,
                "fund": fund,
                "status": status,
                "lines_found": len(row.lines),
                "checks_found": row.check_count,
                "note": "; ".join(row.notes) or None,
            }
        )

    mark_cumulative(sets)

    sets_by_date: dict[str, list[SetRow]] = defaultdict(list)
    for row in sets:
        sets_by_date[row.artifact.meeting_date].append(row)
    recon_rows = reconcile_against_register(sets_by_date, registers, recaps)

    all_lines = [line for row in sets for line in row.lines]
    set_dates = {row.set_id: date.fromisoformat(row.artifact.meeting_date) for row in sets if row.artifact.meeting_date}
    vendors = build_vendors(all_lines, set_dates)

    set_rows = [
        {
            "set_id": row.set_id,
            "meeting_date": row.artifact.meeting_date,
            "fund": row.fund,
            "source_document_id": row.artifact.document_id,
            "agenda_item_document_id": agenda_by_date.get(row.artifact.meeting_date),
            "doc_class": row.artifact.doc_class,
            "format_era": row.parsed.era,
            "period_start": row.parsed.period[0],
            "period_end": row.parsed.period[1],
            "pcard_period_start": row.parsed.pcard_period[0],
            "pcard_period_end": row.parsed.pcard_period[1],
            "stated_total": row.stated_total,
            "parsed_total": row.parsed_total,
            "sum_check_dedup": row.sum_check_dedup,
            "line_count": len(row.lines),
            "check_count": row.check_count,
            "hash_total": row.hash_total,
            "reconciled": row.reconciled,
            "delta": row.delta,
            "reason_code": row.reason_code,
            "notes": "; ".join(row.notes) or None,
            "source": source_kind(row.artifact.resolved_path),
            "locator_document_id": row.artifact.document_id,
            "locator_file_path": row.artifact.resolved_path,
            "locator_file_sha256": row.artifact.sha256,
            "locator_page": None,
            "locator_char_offset": row.parsed.stated_total_offset,
            "locator_quote": None,
        }
        for row in sets
    ]
    # Locator page and quote for the TOTAL line, resolved per set. Without
    # the page the export prints an em dash exactly where a director would
    # look to check the number against the document.
    for row, out in zip(sets, set_rows, strict=True):
        out["locator_page"] = row.stated_total_page
        if row.parsed.stated_total_offset is None:
            continue
        for label, amount, offset in row.parsed.totals:
            if offset == row.parsed.stated_total_offset:
                out["locator_quote"] = f"{label} {amount}"
                break

    print(
        f"sets={len(set_rows)} lines={len(all_lines)} vendors={len(vendors)} "
        f"reconciliations={len(recon_rows)} parse_log={len(logs)}"
    )
    if args.dry_run:
        return

    with db.connect() as conn:
        with conn.cursor() as cur:
            if args.reload:
                # Only facts tables. Nothing outside schema facts is touched.
                cur.execute("DELETE FROM facts.voucher_reconciliation")
                cur.execute("DELETE FROM facts.voucher_line")
                cur.execute("DELETE FROM facts.voucher_set")
                cur.execute("DELETE FROM facts.vendor")
                cur.execute("DELETE FROM facts.voucher_parse_log")
            _insert(cur, "facts", "voucher_set", SET_COLUMNS, set_rows)
            _insert(cur, "facts", "voucher_line", LINE_COLUMNS, all_lines)
            _insert(cur, "facts", "vendor", VENDOR_COLUMNS, vendors)
            _insert(cur, "facts", "voucher_reconciliation", RECON_COLUMNS, recon_rows)
            _insert(cur, "facts", "voucher_parse_log", LOG_COLUMNS, logs)
    print("loaded")


if __name__ == "__main__":
    main()
